#!/usr/bin/env python3
"""Refresh schema/mitre_enterprise.json from the MITRE ATT&CK Enterprise STIX bundle.

Run periodically (e.g. a scheduled pipeline) and commit the refreshed file.
Can also be run locally: `make refresh-mitre`.

Output schema matches what validate_rules.py expects:
    {"generated_at": "YYYY-MM-DDTHH:MM:SSZ", "tactics": [...], "techniques": [...]}
"""
from __future__ import annotations

import datetime as dt
import json
import sys
from pathlib import Path

import requests

REPO_ROOT = Path(__file__).resolve().parent.parent
OUTPUT = REPO_ROOT / "schema" / "mitre_enterprise.json"

# Stable GitHub-hosted STIX bundle, maintained by MITRE.
STIX_URL = "https://raw.githubusercontent.com/mitre/cti/master/enterprise-attack/enterprise-attack.json"


def fetch_bundle() -> dict:
    resp = requests.get(STIX_URL, timeout=60)
    resp.raise_for_status()
    return resp.json()


def extract(bundle: dict) -> tuple[list[str], list[str]]:
    """Return (tactics, techniques). Tactics include BOTH the human-readable name
    ("Initial Access") and the ATT&CK ID ("TA0001") because Falcon stores rules
    using the ID form while analysts write rules using the name form."""
    tactics: set[str] = set()
    techniques: set[str] = set()
    for obj in bundle.get("objects", []):
        if obj.get("revoked") or obj.get("x_mitre_deprecated"):
            continue
        otype = obj.get("type")
        if otype == "x-mitre-tactic":
            name = obj.get("name")
            if name:
                tactics.add(name)
            for ref in obj.get("external_references", []) or []:
                if ref.get("source_name") == "mitre-attack":
                    ext_id = ref.get("external_id")
                    if ext_id and ext_id.startswith("TA"):
                        tactics.add(ext_id)
        elif otype == "attack-pattern":
            for ref in obj.get("external_references", []) or []:
                if ref.get("source_name") == "mitre-attack":
                    ext_id = ref.get("external_id")
                    if ext_id and ext_id.startswith("T") and not ext_id.startswith("TA"):
                        techniques.add(ext_id)
    return sorted(tactics), sorted(techniques)


def main() -> int:
    print(f"fetching {STIX_URL} ...")
    bundle = fetch_bundle()
    tactics, techniques = extract(bundle)
    payload = {
        "$comment": "Generated by scripts/refresh_mitre.py. Do not hand-edit.",
        "generated_at": dt.datetime.now(dt.timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ"),
        "tactics": tactics,
        "techniques": techniques,
    }
    with OUTPUT.open("w") as f:
        json.dump(payload, f, indent=2)
        f.write("\n")
    print(f"wrote {OUTPUT.relative_to(REPO_ROOT)} - "
          f"{len(tactics)} tactics, {len(techniques)} techniques.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
